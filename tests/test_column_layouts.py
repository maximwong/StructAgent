class LayoutToolTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.output = Path(self.tmp.name)
        self.store = ColumnLayoutStore(self.output / 'column-layout-designs')
        self.design = ColumnLayoutDesignTool(self.store)
        self.check = ColumnLayoutCheckTool(self.store)

    def tearDown(self): self.tmp.cleanup()

    def test_reference_isolation_repeated_runs_and_actual_check(self):
        request = envelope('design_column_layouts', parameters(), 'LAYOUT-TEST')
        one, two = self.design.execute(request), self.design.execute(request)
        self.assertTrue(one.success, one.errors)
        self.assertTrue(two.success, two.errors)
        ref = one.result['design_result_ref']
        self.assertNotEqual(ref, two.result['design_result_ref'])
        checked = self.check.execute(envelope('check_column_layouts', {'design_result_ref': ref}, 'LAYOUT-TEST'))
        self.assertTrue(checked.success, checked.errors)
        self.assertEqual(checked.result['actual'], one.result['selected']['actual'])
        self.assertFalse(self.check.execute(envelope('check_column_layouts', {'design_result_ref': ref}, 'OTHER')).success)
        for wrong in ('column-' + 'a'*32, 'column-set-' + 'a'*32, '../bad'):
            self.assertFalse(self.check.execute(envelope('check_column_layouts', {'design_result_ref': wrong}, 'LAYOUT-TEST')).success)

    def test_snapshot_tamper_even_with_rehashed_envelope(self):
        result = self.design.execute(envelope('design_column_layouts', parameters(), 'LAYOUT-TEST'))
        ref = result.result['design_result_ref']
        path = self.store.root / (ref + '.json')
        data = json.loads(path.read_text(encoding='utf-8'))
        report = data['design']['result']
        report['selected']['combination_results'][0]['report']['faces'][0]['area_mm2'] += 1
        data['design']['metadata']['column_layout_sha256'] = canonical_hash({k:v for k,v in report.items() if k!='design_result_ref'})
        data['checksum'] = canonical_hash({k:v for k,v in data.items() if k!='checksum'})
        path.write_text(json.dumps(data), encoding='utf-8')
        with self.assertRaises(ColumnLayoutReferenceError): self.store.load(ref, project_id='LAYOUT-TEST')

    def test_check_rejects_swapped_actual_dropped_groups_and_unverified_reference(self):
        p = parameters()
        actual = candidate_actual('eight_perimeter', 14)
        for mutation in ('swap', 'drop', 'reference'):
            r = check_column_layouts(p, actual)
            if mutation == 'swap': r = check_column_layouts(p, candidate_actual('eight_perimeter', 16))
            elif mutation == 'drop': r['combination_results'].pop()
            else: r['design_result_ref'] = 'column-layout-'+'a'*32
            with patch('tools.column.layout_tools.check_column_layouts', return_value=r):
                checked = self.check.execute(envelope('check_column_layouts', {**p, 'actual': actual}, 'LAYOUT-TEST'))
            self.assertFalse(checked.success)
            self.assertEqual(checked.errors[0]['code'], 'column_layouts_check_invalid')

    def test_design_rejects_unauthorized_prefix_and_preserves_fail_output(self):
        p = parameters(layouts=['six_b'])
        failed = self.design.execute(envelope('design_column_layouts', p, 'LAYOUT-TEST'))
        self.assertFalse(failed.success)
        self.assertEqual(len(failed.result['attempts']), 8)
        self.assertFalse(self.store.root.exists())
        r = design_column_layouts(parameters())
        r['attempts'].pop(0)
        with self.assertRaises(ValueError): validate_design_semantics(r)

    def test_missing_and_cross_project_references_never_recompute_design(self):
        with patch('tools.column.layout_tools.design_column_layouts', side_effect=AssertionError('no redesign')):
            checked = self.check.execute(envelope('check_column_layouts',
                {'design_result_ref': 'column-layout-' + 'a'*32}, 'LAYOUT-TEST'))
        self.assertFalse(checked.success)
        self.assertEqual(checked.errors[0]['code'], 'invalid_column_layouts_reference')

    def test_controller_workflow_plugins_no_side_effects_and_failed_design_stops(self):
        before = (ROOT/'agent/controller.py').read_bytes()
        with patch('tools.column.layout_calculation.check_column', side_effect=AssertionError('load must not compute')):
            catalog = load_plugins(ROOT/'plugins', PluginContext(self.output))
        self.assertIn('design_floor_system', {t['name'] for t in catalog.registry.list_tools()})
        snapshot = run_request(envelope('design_column_layouts', parameters(), 'LAYOUT-TEST'), self.output)
        self.assertTrue(snapshot['success'], snapshot['errors'])
        self.assertEqual(snapshot['steps'], {'parse': 'completed', 'design': 'completed', 'check': 'completed'})
        failed = run_request(envelope('design_column_layouts', parameters(layouts=['six_b']), 'LAYOUT-TEST'), self.output)
        self.assertFalse(failed['success'])
        self.assertEqual(failed['steps']['check'], 'skipped')
        self.assertEqual(before, (ROOT/'agent/controller.py').read_bytes())

    def test_cli_examples_and_strict_json(self):
        for name, code, mode in [('four', 0, False), ('six-b', 0, False), ('six-h', 0, False),
                ('eight', 0, False), ('check-fail', 1, True), ('ties-fail', 1, True), ('design-fail', 1, False)]:
            command = [sys.executable, '-m', 'examples.column_layouts', '--request-file',
                str(ROOT/f'demos/column-layouts-{name}.json'), '--output-root', str(self.output)]
            if mode: command.append('--tool-only')
            proc = subprocess.run(command, cwd=ROOT, capture_output=True, timeout=60)
            self.assertEqual(proc.returncode, code, proc.stderr)
            snapshot = json.loads(proc.stdout.decode('utf-8'))
            self.assertEqual(snapshot['success'], code == 0)
        invalid = self.output / 'invalid.json'
        invalid.write_text('{"project_id":"A","project_id":"B"}', encoding='utf-8')
        proc = subprocess.run([sys.executable, '-m', 'examples.column_layouts', '--request-file', str(invalid)],
            cwd=ROOT, capture_output=True, timeout=30)
        self.assertEqual(proc.returncode, 1)
        self.assertEqual(json.loads(proc.stdout.decode('utf-8'))['status'], 'invalid_input')


